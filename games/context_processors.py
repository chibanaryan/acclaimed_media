"""
Custom template context processors.
"""

from games.models import Subscriber


def csp_nonce(request):
    """
    Add CSP nonce to template context.

    The nonce is generated by CSPMiddleware and attached to the request.
    """
    return {"csp_nonce": getattr(request, "csp_nonce", "")}


def user_subscription(request):
    """
    Add subscription status to template context for authenticated users.
    """
    is_subscribed = False
    if request.user.is_authenticated and request.user.email:
        is_subscribed = Subscriber.objects.filter(
            email=request.user.email,
            is_confirmed=True,
            is_active=True,
        ).exists()
    return {"is_subscribed": is_subscribed}
